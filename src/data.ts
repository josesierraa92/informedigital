const parseCsv = (raw: string): Lead[] => {
  const lines = raw.trim().split('\n');
  if (lines.length < 2) return [];

  const headers = lines[0].split(';').map(h => h.trim().toLowerCase());
  const indexOf = (colName: string) => headers.indexOf(colName);

  // Índice de cada campo según la cabecera de ESTE csv.
  const idx = {} as Record<keyof Lead, number>;
  (Object.keys(CSV_COLUMNS) as (keyof Lead)[]).forEach(field => {
    idx[field] = indexOf(CSV_COLUMNS[field]);
  });

  const leads: Lead[] = [];
  for (let i = 1; i < lines.length; i++) {
    const parts = lines[i].split(';');
    if (parts.length < 10) continue;

    const lead = {} as Lead;
    (Object.keys(idx) as (keyof Lead)[]).forEach(field => {
      const at = idx[field];
      lead[field] = (at >= 0 && at < parts.length ? parts[at] : '').trim();
    });
    leads.push(lead);
  }
  return leads;
};

