export const getAdvisorStats = (leads: Lead[]) => {
  const stats: Record<string, { total: number, won: number, evaluating: number, lost: number }> = {};
  leads.forEach(l => {
    const adv = l.advisor || 'Sin Asesor';
    if (!stats[adv]) stats[adv] = { total: 0, won: 0, evaluating: 0, lost: 0 };
    stats[adv].total++;
    
    const status = l.status.toLowerCase();
    if (status === 'ganado') {
      stats[adv].won++;
    } else if (status === 'perdido') {
      stats[adv].lost++;
    } else {
      stats[adv].evaluating++;
    }
  });
  return Object.entries(stats).map(([name, data]) => ({
    name,
    total: data.total,
    won: data.won,
    evaluating: data.evaluating,
    lost: data.lost,
    conversion: data.total > 0 ? ((data.won / data.total) * 100).toFixed(1) : '0.0'
  })).sort((a,b) => b.total - a.total);
};
